#!/usr/bin/env bash
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

out="assets/css/core.css"

files=(
    assets/css/base/variables.css
    assets/css/base/reset.css
    assets/css/base/typography.css
    assets/css/base/global.css
    assets/css/base/utilities.css
    assets/css/components/header.css
    assets/css/components/navigation.css
    assets/css/components/buttons.css
    assets/css/components/search.css
    assets/css/components/filter-tabs.css
    assets/css/components/breadcrumbs.css
    assets/css/components/footer.css
    assets/css/components/banner.css
    assets/css/components/back-to-top.css
)

{
    printf '/* Generated by bin/build-core-css.sh. Do not edit directly. */\n'
    for file in "${files[@]}"; do
        printf '\n/* ===== %s ===== */\n' "$file"
        if [[ "$file" == "assets/css/base/typography.css" ]]; then
            sed 's#\.\./\.\./fonts/#../fonts/#g' "$file"
        else
            cat "$file"
        fi
        printf '\n'
    done
} > "$out"

printf 'Built %s\n' "$out"
